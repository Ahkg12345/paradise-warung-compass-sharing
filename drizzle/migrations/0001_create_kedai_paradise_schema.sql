CREATE OR REPLACE FUNCTION public.set_menu_code()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_prefix text;
  v_counter integer;
BEGIN
  v_prefix := 'KP-' || upper(left(regexp_replace(split_part(trim(NEW.name), ' ', 1), '[^[:alnum:]]', '', 'g'), 3));
  IF v_prefix = 'KP-' THEN
    RAISE EXCEPTION 'Menu name must start with a letter or number';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('menu-code:' || v_prefix, 0));
  SELECT coalesce(max(substring(code FROM (char_length(v_prefix) + 2))::integer), 0) + 1
  INTO v_counter
  FROM public.menu
  WHERE code LIKE v_prefix || '-%';
  NEW.code := v_prefix || '-' || lpad(v_counter::text, 2, '0');
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.set_menu_code() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER menu_generate_code_before_insert BEFORE INSERT ON public.menu FOR EACH ROW EXECUTE FUNCTION public.set_menu_code();

CREATE OR REPLACE FUNCTION public.prevent_menu_code_change()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.code IS DISTINCT FROM OLD.code THEN
    RAISE EXCEPTION 'Menu code is immutable';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.prevent_menu_code_change() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER menu_code_immutable_before_update BEFORE UPDATE ON public.menu FOR EACH ROW EXECUTE FUNCTION public.prevent_menu_code_change();

